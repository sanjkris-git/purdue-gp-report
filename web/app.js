$('note-zones').textContent = `The ${R.zones.length} zones account for about ${S.zones_total_s.toFixed(2)} s of the ${S.loss_total_s.toFixed(2)} s an average push lap loses to the best line. Switch to Time lost to see the whole lap as a heat map. Lost s and speed are averages over push laps; video time is the best lap, so you can watch each zone.`;
